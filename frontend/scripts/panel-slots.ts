/**
 * npm run panels
 *
 * Writes images/IMAGE-LIST.md — a checklist of every picture slot on the
 * site, marked ✅ when a matching image is in the folder — and refreshes
 * credits.schema.json so VS Code autocompletes slot names in credits.json.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { listSlots } from '../src/data/slots';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '../../images');
const IMAGE = /\.(jpe?g|png|webp|avif|gif)$/i;

const files = readdirSync(dir).filter((f) => IMAGE.test(f));
const byKey = new Map(files.map((f) => [f.replace(/\.[^.]+$/, '').toLowerCase(), f]));
const slots = listSlots();
const keys = new Set(slots.map((s) => s.key));

const filled = slots.filter((s) => byKey.has(s.key)).length;
const unknown = files.filter((f) => !keys.has(f.replace(/\.[^.]+$/, '').toLowerCase()));

/** The pictures people see first — listed on top so they can be done first. */
const START_HERE = ['cover', 'home-logo', 'home-struggler', 'home-golden-age', 'home-world', 'guts', 'griffith', 'casca', 'skull-knight', 'puck', 'legacy-miura', 'ev-eclipse'];

const SIZE: Record<string, string> = {
  portrait: 'tall, about 1200×1600',
  landscape: 'wide, about 1600×1000',
  square: 'square, about 1200×1200',
  'tall strip': 'narrow & tall, about 600×1600',
  'wide strip': 'very wide, about 1800×600',
};

const row = (s: (typeof slots)[number]) => {
  const f = byKey.get(s.key);
  return `| ${f ? '✅' : '⬜'} | \`${f ?? `${s.key}.jpg`}\` | ${s.where.replace(/\|/g, '/')} | ${SIZE[s.shape] ?? s.shape} |`;
};
const HEAD = ['| | Save the picture as | Where it shows on the site | Shape |', '|---|---|---|---|'];

const lines: string[] = [
  '# Images to add',
  '',
  '<!-- Generated by `npm run panels`. Do not edit by hand. -->',
  '',
  `**${filled} of ${slots.length} added.** ⬜ = still needed · ✅ = done`,
  '',
  '**How:** save the picture in this `images/` folder with the exact name from the list,',
  'then reload the site. `.jpg` `.png` `.webp` `.avif` all work — only the name before the dot matters.',
  'Afterwards run **Terminal → Run Task… → Images: update the list** to tick it off here.',
  '',
  'Only add pictures you made, own, or have the artist’s permission to publish — this repository is public.',
  'Put the artist’s name in `credits.json` (see README.md).',
  '',
];

if (unknown.length) {
  lines.push('## ⚠️ These files match no name (check the spelling)', '', 'They are not shown anywhere on the site:', '');
  for (const f of unknown) lines.push(`- \`${f}\``);
  lines.push('');
}

const first = START_HERE.map((k) => slots.find((s) => s.key === k)).filter((s): s is (typeof slots)[number] => !!s);
lines.push('## ⭐ Start here — the most visible pictures', '', ...HEAD, ...first.map(row), '');
lines.push('---', '', '## Everything else, page by page', '');

const sections = [...new Set(slots.map((s) => s.section))];
for (const section of sections) {
  const rows = slots.filter((s) => s.section === section);
  const done = rows.filter((s) => byKey.has(s.key)).length;
  lines.push(`### ${section} — ${done}/${rows.length}`, '', `Open on the site: \`${rows[0].page}\``, '', ...HEAD, ...rows.map(row), '');
}

writeFileSync(join(dir, 'IMAGE-LIST.md'), lines.join('\n'));

const schema = {
  $schema: 'http://json-schema.org/draft-07/schema#',
  title: 'Panel image credits',
  type: 'object',
  properties: {
    $schema: { type: 'string' },
    _help: { type: 'string' },
    credits: {
      type: 'object',
      description: 'Key = image file name without extension.',
      propertyNames: { enum: [...keys] },
      additionalProperties: {
        type: 'object',
        additionalProperties: false,
        properties: {
          alt: { type: 'string', description: 'What the picture shows (for screen readers).' },
          credit: { type: 'string', description: 'Artist / owner, e.g. "Fan art by @name".' },
          license: { type: 'string', description: 'e.g. "Used with permission", "CC BY 4.0", "Own work".' },
          sourceUrl: { type: 'string', description: 'Where the picture came from.' },
        },
      },
    },
  },
};
writeFileSync(join(dir, 'credits.schema.json'), JSON.stringify(schema, null, 2) + '\n');

console.log(`Image slots: ${filled}/${slots.length} filled → images/IMAGE-LIST.md`);
if (unknown.length) console.log(`⚠  ${unknown.length} file(s) match no slot: ${unknown.join(', ')}`);
